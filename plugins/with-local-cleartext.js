const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/**
 * Permits cleartext HTTP to the developer's own machine, and nowhere else.
 *
 * The end-to-end suite drives a backend running on localhost, reached through
 * `adb reverse`. Android has refused cleartext by default since API 28, so
 * without this the app's requests fail before leaving the device and it reports
 * "could not reach the server" — which is true and says nothing about why. That
 * cost an hour, and the manifest edit that fixed it lived in `android/`, which is
 * generated and not committed, so it would have been lost at the next prebuild.
 *
 * A scoped config rather than `usesCleartextTraffic: true`: `10.0.2.2` is the
 * host as seen from an emulator, `localhost` is the device itself, and neither is
 * routable from anywhere else — so this costs nothing in a shipped build, while
 * blanket permission would weaken every request the app makes.
 */
const CONFIG_FILE = 'network_security_config.xml';

const CONFIG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-local-cleartext.js. Edit that, not this. -->
<network-security-config>
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">10.0.2.2</domain>
    <domain includeSubdomains="false">localhost</domain>
    <domain includeSubdomains="false">127.0.0.1</domain>
  </domain-config>
</network-security-config>
`;

module.exports = function withLocalCleartext(config) {
  config = withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const target = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      fs.mkdirSync(target, { recursive: true });
      fs.writeFileSync(path.join(target, CONFIG_FILE), CONFIG_XML, 'utf8');
      return modConfig;
    },
  ]);

  return withAndroidManifest(config, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(modConfig.modResults);
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return modConfig;
  });
};
